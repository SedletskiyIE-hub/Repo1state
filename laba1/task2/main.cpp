//Дано натуральное K — количество секунд. Определить сколько это
//составляет часов, минут и секунд. Например, 4000 секунд — это 1 час, 6
//минут и 40 секунд.

#include <iostream>


int main(){

    int k = 4000;
    unsigned short h, m, s;

    h = k / 3600;
    m = k % 3600 / 60;
    s = k % 60;

    printf("часы: %u\n", h);
    printf("минуты: %u\n", m);
    printf("секунды: %u\n", s);

    return 0;

}
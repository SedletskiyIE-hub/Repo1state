//Определить сколько лет понадобится России, чтобы собрать
//урожай зерна, требуемый изобретателем шахмат. Считать, что
//среднегодовой сбор составляет 70 млн. тонн, а на 1 грамм приходится 10
//зерен.

#include <iostream>
#include <math.h>


int main() {

    double k = ~0ULL;
    unsigned short s;

    s = ceil(k / 7e14);

    printf("Количество лет: %u\n", s);
    
    return 0;
    
}